"""Build the marker / logo icon masks from the source drawings and embed them in the template.

Sources (owner's drawings, same canvas so the cone lines up):
    trmnl/assets/icons/lava-source.png      heat detected (thermal anomaly only)
    trmnl/assets/icons/eruption-source.png  eruption confirmed by an official source

For each, two alpha masks are written (shape, and a dilated "halo" for the white
outline) and embedded as CSS custom properties in trmnl/src/shared.liquid, where the
marker paints them with TRMNL framework classes (so the shade-by-age still works).

Needs ImageMagick (`convert`).  python scripts/build_icons.py
"""

import base64
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ICONS = REPO / "trmnl" / "assets" / "icons"
TEMPLATE = REPO / "trmnl" / "src" / "shared.liquid"
CROP = "1205x1166+12+68"   # common frame of both drawings (plume included)
PAD = 70                   # source px of room for the halo
HALO = 45                  # halo radius, source px
SIZE = 128                 # output width, px


def mask(src: Path, out: Path, halo: bool) -> bytes:
    cmd = ["convert", str(src), "-crop", CROP, "+repage", "-colorspace", "Gray", "-threshold", "50%",
           "-negate", "-bordercolor", "black", "-border", str(PAD)]
    if halo:
        cmd += ["-morphology", "Dilate", f"Disk:{HALO}"]
    cmd += ["-resize", f"{SIZE}x", "-threshold", "50%", "-alpha", "copy", "-channel", "RGB",
            "-evaluate", "set", "0", "+channel", "-strip", str(out)]
    subprocess.run(cmd, check=True)
    return out.read_bytes()


def main() -> None:
    css = []
    for name, key in (("lava", "lava"), ("eruption", "erupt")):
        for halo in (False, True):
            suffix = "-halo" if halo else ""
            data = mask(ICONS / f"{name}-source.png", ICONS / f"{name}{suffix}.png", halo)
            css.append(f"  --hs-{key}{suffix}: url(data:image/png;base64,{base64.b64encode(data).decode()});")
            print(f"{name}{suffix}: {len(data)} bytes")
    block = "  /* icon masks: generated by backend/scripts/build_icons.py */\n  :root {\n" + "\n".join(css) + "\n  }\n"
    text = TEMPLATE.read_text()
    new, n = re.subn(r"  /\* icon masks: generated by backend/scripts/build_icons\.py \*/\n  :root \{\n.*?\n  \}\n",
                     lambda m: block, text, flags=re.S)
    if n == 0:
        new, n = text.replace("<style>\n", "<style>\n" + block, 1), 1
    TEMPLATE.write_text(new)
    print(f"embedded in {TEMPLATE}")


if __name__ == "__main__":
    main()
